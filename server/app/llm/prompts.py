"""Сборка промптов для LLM.

Модуль намеренно «чистый»: не знает ни про Settings, ни про роутер — только
данные на входе и строки на выходе. Кто мы сейчас, решают вызывающие:
- режим встречи (`mode`) приходит из БД/WS-команды;
- `detailed` — от провайдера (локальная модель ↔ API, см. LlmRouter.budget);
- `allow_skip` — от способа вызова (авто ↔ кнопка «Подсказать сейчас»).

Главное правило подсказок: модель имеет право промолчать (ответить SKIP).
Раньше она была обязана выдавать подсказку каждые ~15 секунд и в отсутствие
полезного рожала воду — молчание лечит это лучше любой формулировки.
"""
from dataclasses import dataclass

# --------------------------------------------------------------- режимы встречи


@dataclass(frozen=True)
class MeetingMode:
    key: str
    label: str             # подставляется в промпт и показывается в UI
    hint_focus: str        # на что смотреть в этом типе встречи (коротко!)


MODES: dict[str, MeetingMode] = {
    "work": MeetingMode(
        key="work",
        label="рабочая встреча / планёрка",
        hint_focus=(
            "Следи за задачами без ответственного и срока, за решениями без критерия "
            "готовности, за блокерами и зависимостями, которые упомянули и не разобрали."
        ),
    ),
    "interview": MeetingMode(
        key="interview",
        label="собеседование (ты помогаешь тому, кто проходит собеседование)",
        hint_focus=(
            "Владелец микрофона — кандидат, помогай ему. Если интервьюер задал "
            "вопрос — дай суть ответа тезисами. Если прозвучал незнакомый термин "
            "или технология — коротко объясни. Замечай вопросы, которые стоит "
            "задать самому (задачи, команда, процессы, условия)."
        ),
    ),
    "negotiation": MeetingMode(
        key="negotiation",
        label="переговоры",
        hint_focus=(
            "Следи за условиями (цена, сроки, объём) и их изменениями по ходу, за "
            "уступкой без встречной уступки, за расплывчатыми обязательствами "
            "(«постараемся», «в ближайшее время»), за незаданными вопросами о "
            "бюджете, полномочиях и сроке решения."
        ),
    ),
}

DEFAULT_MODE = "work"


def normalize_mode(value: str | None) -> str:
    """Любой мусор/None/старый клиент без поля → режим по умолчанию."""
    return value if value in MODES else DEFAULT_MODE


def mode_label(key: str | None) -> str:
    return MODES[normalize_mode(key)].label


# --------------------------------------------------------------- подсказки

SKIP_TOKEN = "SKIP"

_HINT_ROLE = """\
Ты — молчаливый ассистент на встрече. Ты видишь расшифровку разговора в реальном
времени и вмешиваешься ТОЛЬКО когда действительно есть что сказать."""

_HINT_CATEGORIES = """\
Разрешены ровно пять типов подсказки:
1. ОТВЕТ — прозвучал прямой вопрос, на который никто не ответил (в том числе
   «что такое X?»). Дай ответ ПО СУЩЕСТВУ, а не совет у кого-то спросить.
2. ТЕРМИН — прозвучали термин или аббревиатура, которые часть участников может
   не знать. Дай короткое определение.
3. РИСК — в сказанном есть противоречие, фактическая ошибка или неучтённый риск.
4. ПРОБЕЛ — важный вопрос задали, но обсуждение ушло в сторону; или решение
   приняли без ключевого условия.
5. ЗАДАЧА — прозвучала договорённость без ответственного или без срока."""

_HINT_RULES = """\
Правила:
- Одна подсказка. Максимум два предложения. Пиши по-русски.
- Без вступлений («Подсказка:», «Совет:», «Обратите внимание:»).
- Не пересказывай то, что и так только что сказали.
- Не выдумывай факты. Не уверен в ответе — не отвечай.
- Не задавай вопрос ради вопроса."""

# Распознавание речи русское и английские термины коверкает. Без этой оговорки
# модель честно объясняет, что такое «уд», хотя спрашивали про UDP.
_ASR_NOISE_WARNING = """\
Важно про транскрипт: он получен русским распознаванием речи, и английские
термины с аббревиатурами в нём часто искажены — «UDP» может выглядеть как «уд»
или «юдипи», «API» как «апи», «Kubernetes» как «кубернетес». Если слово похоже
на исковерканный технический термин, восстанови его по смыслу разговора и
отвечай про настоящий термин. Если догадаться не получается — не угадывай."""

_HINT_SKIP_RULE = f"""\
Если ни один из пяти типов не подходит — ответь ровно одним словом: {SKIP_TOKEN}.
Молчать нормально. {SKIP_TOKEN} лучше, чем бесполезная подсказка."""

_HINT_FORCE_RULE = """\
Пользователь явно нажал «Подсказать сейчас» — ответ обязателен.
Выбери самое полезное из пяти типов. Если ничего критичного нет — одним
предложением скажи, на чём разговор сейчас и какой следующий шаг напрашивается."""

# Примеры (первые два + SKIP-пример идут всегда; остальные — только в detailed).
# SKIP-пример обязателен: без него модель считает молчание отказом от работы.
_HINT_EXAMPLES_CORE = """\
Фрагмент: «Иван: у нас по SLA девять девяток. / Мария: а что такое SLA?»
Хорошо: «SLA — соглашение об уровне сервиса; 99,9 % — это не более ~43 минут простоя в месяц.»
Плохо:  «Уточните у Ивана, что он имеет в виду под SLA.»  ← просит спросить вместо ответа

Фрагмент: «Пётр: релиз выкатим в пятницу. / Анна: ок.»
Хорошо: «Релиз в пятницу — кто дежурит на выходных, если что-то отвалится?»
Плохо:  «Обсудите план релиза подробнее.»  ← вода"""

_HINT_EXAMPLES_EXTRA = """\
Фрагмент: «Аня: я пришлю макеты. / Олег: спасибо.»
Хорошо: «У задачи «прислать макеты» нет срока — до какого числа?»

Фрагмент: «Игорь: база у нас на одном сервере, реплики нет. / Лиза: ну ок, потом добавим.»
Хорошо: «База без реплики — единая точка отказа; стоит зафиксировать это как риск с владельцем.»"""

_HINT_EXAMPLE_SKIP = f"""\
Фрагмент: «Иван: …а мы на неделю в отпуск съездили. / Мария: здорово!»
Хорошо: {SKIP_TOKEN}"""


_ANSWER_ROLE = """\
Ты — ассистент участника встречи. Он идёт прямо сейчас, участник задал тебе
вопрос и, возможно, показал, о каких репликах речь. Ответь ему."""

_ANSWER_RULES = """\
Правила:
- Отвечай ИСКЛЮЧИТЕЛЬНО на русском языке, даже если реплики в транскрипте
  частично на другом.
- По существу и коротко: обычно двух-трёх предложений хватает. Развёрнутый ответ
  уместен, только если вопрос действительно требует разбора.
- Без вступлений («Отвечаю:», «Конечно!», «Хороший вопрос»).
- Человек читает это посреди разговора и слушает вполуха — сначала суть, потом
  подробности.
- Если ответа в разговоре нет, а вопрос об общеизвестном — ответь из своих
  знаний и пометь это словами «в разговоре об этом не говорили».
- Не выдумывай, что кто-то что-то сказал. Не было — так и скажи."""


def build_answer_prompt(
    *,
    mode: str,
    question: str,
    quoted: str = "",
    earlier: str = "",
    title: str = "",
    participants: str = "",
) -> tuple[str, str]:
    """Возвращает (system, prompt) для ответа на вопрос участника.

    Отдельно от build_hint_prompt намеренно: там модель сама решает, о чём
    говорить, и ограничена пятью типами подсказки. Здесь тему задал человек, и
    подсовывать ему категории — мешать. Общие блоки (тип встречи, предупреждение
    про искажения распознавания) переиспользуются.

    question — что спросил участник;
    quoted — реплики, на которые он показал (может не быть — тогда вопрос общий);
    earlier — остальной разговор для понимания контекста.
    """
    meeting = MODES[normalize_mode(mode)]
    system = "\n\n".join([
        _ANSWER_ROLE,
        f"Тип встречи: {meeting.label}.",
        _ANSWER_RULES,
        _ASR_NOISE_WARNING,
    ])

    header = []
    if title:
        header.append(f"Встреча: «{title}»")
    if participants:
        header.append(f"Участники: {participants}")

    parts = []
    if header:
        parts.append("\n".join(header))
    if earlier:
        parts.append(f"Разговор для контекста:\n\n{earlier}")
    if quoted:
        parts.append(
            "Участник показал именно на эти реплики — вопрос про них:\n\n" f"{quoted}"
        )
    parts.append(f"Вопрос участника:\n{question}")
    parts.append("Твой ответ:")
    return system, "\n\n".join(parts)


def build_hint_prompt(
    *,
    mode: str,
    transcript: str,
    previous: str,
    earlier: str = "",
    title: str = "",
    participants: str = "",
    detailed: bool = False,
    allow_skip: bool = True,
) -> tuple[str, str]:
    """Возвращает (system, prompt) для подсказки.

    transcript — то, на что НАДО реагировать (новое с прошлой подсказки).
    earlier — что было до этого: нужно, чтобы понимать разговор, но реагировать
        не надо. Внутри отмечено, где ассистент уже подсказывал, — иначе модель
        видит старый вопрос как открытый и отвечает на него второй раз.
    detailed — развёрнутый вариант для API (контекст не жалеем);
    allow_skip=False — кнопка «Подсказать сейчас», ответ обязателен.
    """
    meeting = MODES[normalize_mode(mode)]
    system_parts = [
        _HINT_ROLE,
        _HINT_CATEGORIES,
        f"Тип встречи: {meeting.label}.\n{meeting.hint_focus}",
        _HINT_RULES,
        _ASR_NOISE_WARNING,
        _HINT_SKIP_RULE if allow_skip else _HINT_FORCE_RULE,
    ]
    system = "\n\n".join(system_parts)

    examples = [_HINT_EXAMPLES_CORE]
    if detailed:
        examples.append(_HINT_EXAMPLES_EXTRA)
    if allow_skip:  # в force-режиме пример с SKIP только собьёт модель
        examples.append(_HINT_EXAMPLE_SKIP)

    header = []
    if title:
        header.append(f"Встреча: «{title}»")
    if participants:
        header.append(f"Участники: {participants}")

    prompt_parts = ["Примеры.\n\n" + "\n\n".join(examples)]
    if header:
        prompt_parts.append("\n".join(header))
    if earlier:
        prompt_parts.append(
            "Ранее в разговоре — только для понимания контекста, реагировать на это "
            "НЕ надо (в квадратных скобках — что ты уже подсказывал):\n\n"
            f"{earlier}"
        )
        prompt_parts.append(
            f"НОВОЕ с прошлой подсказки — реагируй только на это:\n\n{transcript}"
        )
    else:
        prompt_parts.append(f"Последний фрагмент обсуждения:\n\n{transcript}")
    prompt_parts.append(
        "Ты уже давал такие подсказки — не повторяй их и не пиши похожее по смыслу:\n"
        f"{previous}"
    )
    prompt_parts.append("Твоя подсказка:")
    return system, "\n\n".join(prompt_parts)


_STRIP_CHARS = " \t\n\r`*_\"'«»"
_HINT_PREFIXES = ("подсказка:", "совет:", "ответ:", "hint:")


def parse_hint(raw: str | None, *, min_chars: int = 12) -> str | None:
    """Разбирает ответ модели. None — «промолчала», такое клиенту не шлём.

    Мелкие модели редко отвечают ровно одним словом, поэтому разбор толерантный.
    Но и не слишком жадный: подсказка, где слово skip встречается внутри текста,
    должна дойти до пользователя целиком.
    """
    if not raw:
        return None  # пусто — в т.ч. когда весь ответ ушёл в <think> и его вырезали
    text = raw.strip().strip(_STRIP_CHARS).strip()
    lowered = text.lower()
    for prefix in _HINT_PREFIXES:
        if lowered.startswith(prefix):
            text = text[len(prefix):].strip()
            if text[:1].islower():  # «Подсказка: уточните…» → «Уточните…»
                text = text[0].upper() + text[1:]
            break
    if not text:
        return None
    # SKIP засчитываем, только если это первое слово и после него почти ничего нет
    first, _, rest = text.partition(" ")
    if first.strip(_STRIP_CHARS + ".,!;:—-").upper() == SKIP_TOKEN and len(rest) < 15:
        return None
    if len(text) < min_chars:
        return None  # «Ок.», «Нет.», «—» — считаем молчанием
    return text


# --------------------------------------------------------------- резюме

_PROTOCOL_SECTIONS = """\
## Краткий итог
2–4 предложения: о чём встреча и главный результат.

## Ключевые темы
- о чём говорили, по пунктам

## Задачи
- [ ] [таймкод] что нужно сделать

## Открытые вопросы
- что осталось без ответа"""

_PROTOCOL_SYSTEM = """\
Ты составляешь протокол рабочей встречи по её расшифровке. Пиши ИСКЛЮЧИТЕЛЬНО
на русском, в Markdown, без вступлений и пояснений — только сам протокол.

Чего делать нельзя. Протокол читают те, кого на встрече не было, и проверить его
они не смогут: уверенная выдумка вреднее пропуска.
- Таймкод ставь только скопированный из квадратных скобок нужной реплики.
  Не нашёл — не пиши никакого.
- О чём говорили в прошедшем времени как о сделанном — это результат, а не
  задача: такому место в кратком итоге.
- Предложение, встреченное возражением или уклончивым ответом, задачей не
  становится: ему место в открытых вопросах.
- Ответственных и сроки не пиши вообще. Кто что делает, из расшифровки
  восстанавливается неверно чаще, чем верно.
- Названия и сокращения не достраивай, даже если узнаёшь похожее известное."""

def build_protocol_prompt(
    *,
    mode: str,
    title: str,
    date: str,
    participants: str,
    text: str,
    part: int | None = None,
    total: int | None = None,
) -> tuple[str, str]:
    """Возвращает (system, prompt) для протокола — встречи целиком или фрагмента.

    Один промпт вместо трёх (фрагмент / сведение / целиком) намеренно. Разделы
    протокола раньше зависели от типа встречи, но при лимите 8000 токенов в
    минуту каждая тысяча символов инструкций — это тысяча символов разговора,
    которая не влезла. Своя вёрстка под каждый тип себя не окупала: тип встречи
    остался строкой в шапке, разделы одни на всех.

    part/total — если разбираем фрагмент длинной встречи. Тот же промпт потом
    применяется к склейке протоколов фрагментов: для него это просто текст, по
    которому надо составить протокол.
    """
    meeting = MODES[normalize_mode(mode)]
    system = _PROTOCOL_SYSTEM + "\n\n" + _ASR_NOISE_WARNING

    head = f"Встреча «{title}»"
    if date:
        head += f" ({date})"
    head += f". Тип встречи: {meeting.label}."
    if participants:
        head += f" Участники и число их реплик: {participants}."
    if part:
        head += f" Это фрагмент {part} из {total} — протокол по нему одному."

    prompt = (
        f"{head}\n\nСоставь протокол строго в таком формате:\n\n"
        f"{_PROTOCOL_SECTIONS}\n\nРасшифровка:\n{text}\n"
    )
    return system, prompt
