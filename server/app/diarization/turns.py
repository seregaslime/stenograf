"""Смена говорящего внутри одной реплики — по голосу, а не по тишине и каналу.

Беда, ради которой модуль появился: двое говорят встык в одном канале, пауза
между ними 80–280 мс (замер на записи подкаста), VAD её не видит, и реплики
склеиваются. Отпечаток голоса считается один на двоих, реплику забирает тот,
кто говорил дольше, — «один спикер съедает другого». Порог тишины это не лечит:
при 300 мс VAD режет только с ~400 мс тишины, а опускать нельзя — у людей
запинки внутри фразы те же 200–300 мс. Разрез по смене канала (ws.py) тоже
бессилен: оба голоса идут звуком системы.

Как ищем. Реплика режется на окна по секунде с шагом полсекунды, у каждого
окна считается отпечаток голоса. В каждой точке сравнивается средний голос
пары окон слева со средним голосом пары окон справа; где они не похожи —
говорящий сменился.

Почему именно так — два отвергнутых варианта, оба проверены на записи:
  - сравнивать одиночные соседние окна: окно в секунду шумное, монолог
    рвался бы на каждой просадке голоса;
  - сравнивать всё слева со всем справа: не видит чужой голос островом
    посередине реплики — любой один разрез оставляет смесь по обе стороны.
    На записи это давало зазор 0.005 между «двое» и «один», то есть никакой.
Локальная пара окон с каждой стороны развела их с зазором 0.08.

Модуль не знает ни про библиотеку голосов, ни про владельца: второй человек
может ещё не иметь профиля, и резать надо по смене голоса, а не по совпадению
с кем-то известным. Функция чистая — получает векторы, отдаёт индексы, — чтобы
её можно было проверить без моделей.
"""
import numpy as np

# Окно и шаг, на которых подобран порог speaker_turn_threshold. Поменять их —
# значит перемерить порог: близость средних зависит от длины окна.
WINDOW_S = 1.0
HOP_S = 0.5
# Сколько окон усредняется с каждой стороны от точки. Два окна при шаге 0.5 с —
# это 1.5 с звука: меньше — голос шумит, больше — короткие реплики не проверить
# вовсе (при трёх окнах выпадали все реплики короче 3 с, а зазор не рос).
SIDE_WINDOWS = 2


def _unit(vector: np.ndarray) -> np.ndarray:
    norm = np.linalg.norm(vector)
    return vector / norm if norm > 0 else vector


def local_similarities(windows: np.ndarray, side: int = SIDE_WINDOWS) -> list[tuple[float, int]]:
    """Близость голоса слева и справа в каждой точке реплики: [(близость, k), ...].

    windows — отпечатки голоса окон подряд, форма (n, d), нормированные. Точка k
    лежит между окнами k-1 и k. Пусто, если окон не хватает на пару сторон.

    Отдельной функцией, потому что то же самое считает scripts/eval_turns.py:
    порог подбирается по этим числам, и скрипт с конвейером обязаны получать их
    одним кодом.
    """
    n = len(windows)
    if n < 2 * side:
        return []
    близости = []
    for k in range(side, n - side + 1):
        слева = _unit(windows[k - side:k].mean(axis=0))
        справа = _unit(windows[k:k + side].mean(axis=0))
        близости.append((float(слева @ справа), k))
    return близости


def turn_points(windows: np.ndarray, threshold: float, side: int = SIDE_WINDOWS) -> list[int]:
    """Индексы окон, с которых в реплике начинается другой голос.

    Кандидаты — точки, где близость голоса слева и справа меньше порога. Из
    стоящих рядом берётся самая глубокая, соседи ближе `side` окон
    отбрасываются: окно на стыке смешивает оба голоса, провал тянется на пару
    точек, и без этого одна смена давала бы два разреза, а между ними — огрызок
    в полсекунды.
    """
    выбрано: list[int] = []
    for близость, k in sorted(local_similarities(windows, side)):
        if близость >= threshold:
            break  # дальше только ещё более похожие
        if all(abs(k - уже) >= side for уже in выбрано):
            выбрано.append(k)
    return sorted(выбрано)


def turn_times(windows: np.ndarray, start_s: float, threshold: float) -> list[float]:
    """Моменты смены голоса в секундах от начала записи.

    Провал близости в точке k говорит только, что пара окон слева звучит иначе,
    чем пара справа; сама смена может быть в любом месте окна k-1 или k. Берём
    середину их перекрытия — ошибка до полсекунды.

    Цена этой неточности: слово, попавшее на разрез, делится на два куска звука,
    и распознавание может его исказить. Узнавание говорящего от этого не
    страдает — обе части достаточно длинные, — а вот стык в тексте стоит
    проверять на записи, прежде чем считать разрез безвредным.
    """
    перекрытие = WINDOW_S - HOP_S
    return [start_s + k * HOP_S + перекрытие / 2 for k in turn_points(windows, threshold)]
