"""Типы встречи: только ключи и проверка.

Подписи и указания для модели уехали в приложение вместе с промптами — здесь
осталось то, ради чего тип нужен серверу: он хранится у встречи и должен быть
из известного списка, а не любой строкой из запроса.
"""

MEETING_MODES = ("work", "interview", "negotiation")
DEFAULT_MODE = "work"


def normalize_mode(value: str | None) -> str:
    """Неизвестный или пустой тип — рабочая встреча. Старый клиент поля не шлёт."""
    return value if value in MEETING_MODES else DEFAULT_MODE
