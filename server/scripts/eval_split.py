"""Замер нарезки речи: режет ли VAD реплики двух людей, говорящих встык.

Беда, ради которой скрипт появился: в подкасте второй человек подхватывает
сразу после первого, VAD не видит паузы и склеивает обоих в одну реплику.
Отпечаток голоса считается один на всю реплику, и её целиком забирает тот, кто
в ней говорил дольше, — «один спикер съедает другого».

Разрез по смене канала (ws.py, _split_by_dominance) здесь не помогает: оба
голоса идут звуком системы, канал не меняется. Остаётся порог тишины VAD — и
этот скрипт показывает, что он покупает и чего стоит.

Почему отдельный скрипт, а не regress.py: тот кормит распознаванию готовые
файлы фраз и через VAD не проходит вовсе, то есть на правку порога тишины он
зелёный при любом значении.

Две таблицы:
  1) двое встык с настоящей паузой 0–400 мс — сколько реплик (нужно 2);
  2) монолог одного человека — на сколько кусков его порвало (нужен 1).
Первая про то, что чиним, вторая про то, что можем сломать: слишком низкий
порог рвёт монолог на куски, а короткий кусок даёт худший отпечаток голоса —
узнавание становится хуже, а не лучше.

Голоса синтезированы командой `say`, паузы в монологе расставлены ею же по
границам предложений. Числа показывают поведение нарезки, а не то, какие паузы
бывают в живом разговоре, — финальная проверка на настоящей записи.

Запуск из папки server (только macOS — нужен `say`):
    .venv/bin/python scripts/eval_split.py
"""
import subprocess
import sys
import tempfile
import wave
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.audio.vad import SpeechSegmenter  # noqa: E402
from app.config import SAMPLE_RATE, Settings  # noqa: E402

ПАУЗЫ_МС = (0, 150, 250, 300, 350, 400)
ПОРОГИ_МС = (300, 250, 200, 150)

# Фразы нарочно разной длины: при склейке реплику забирает тот, кто говорил
# дольше, и на равных по длине фразах эта асимметрия не видна.
ПЕРВЫЙ = ("Milena", "Сроки переносим на следующую неделю")
ВТОРОЙ = ("Daniel", "Подождите, я не согласен с таким решением")
МОНОЛОГ = ("Milena", "Давайте по порядку. Сначала обсудим бюджет. Потом сроки. "
                     "И в конце распределим задачи между всеми участниками команды.")


def синтез(папка: Path, голос: str, текст: str) -> np.ndarray:
    путь = папка / f"{голос}_{abs(hash(текст))}.wav"
    subprocess.run(["say", "-v", голос, "-o", str(путь),
                    "--data-format=LEI16@16000", текст], check=True)
    with wave.open(str(путь)) as f:
        звук = np.frombuffer(f.readframes(f.getnframes()), dtype=np.int16).astype(np.float32) / 32768
    return обрезать_тишину(звук)


def обрезать_тишину(звук: np.ndarray, порог: float = 0.01) -> np.ndarray:
    """Срезает тишину по краям фразы.

    `say` оставляет её сам, и не поровну: 38 мс в конце одной фразы и 105 мс в
    начале другой. Без обрезки «пауза 0 мс» в таблице на деле была 143 мс тишины,
    а «200 мс» — 343. Числа выглядели точными и врали. Хуже того, другая версия
    голосов на раннере CI оставляет другую тишину — и тест, поставленный на эти
    числа, зеленел у разработчика и падал в CI.
    """
    громко = np.flatnonzero(np.abs(звук) > порог)
    return звук[громко[0]:громко[-1] + 1] if громко.size else звук


def тишина(мс: int) -> np.ndarray:
    return np.zeros(int(мс * SAMPLE_RATE / 1000), dtype=np.float32)


def реплик(audio: np.ndarray, min_silence_ms: int) -> int:
    """Сколько реплик VAD нарежет из звука, поданного кусками, как на встрече."""
    сегментер = SpeechSegmenter(Settings(_env_file=None, vad_min_silence_ms=min_silence_ms))
    шаг = SAMPLE_RATE // 10
    нарезано = []
    for i in range(0, len(audio), шаг):
        нарезано += сегментер.feed(audio[i:i + шаг])
    # Хвост тишиной: иначе последняя фраза не закроется и не попадёт в счёт
    нарезано += сегментер.feed(тишина(1500))
    return len(нарезано)


def main() -> None:
    текущий = Settings(_env_file=None).vad_min_silence_ms
    пороги = sorted(set(ПОРОГИ_МС) | {текущий}, reverse=True)

    with tempfile.TemporaryDirectory(prefix="stenograf_split_") as tmp:
        папка = Path(tmp)
        print("Синтез голосов...")
        первый = синтез(папка, *ПЕРВЫЙ)
        второй = синтез(папка, *ВТОРОЙ)
        монолог = синтез(папка, *МОНОЛОГ)

    шапка = "".join(f"{p:>7}" + ("*" if p == текущий else " ") for p in пороги)
    print("\n— Двое встык: сколько реплик (нужно 2). Столбцы — порог тишины, мс; * текущий")
    print(f"  {'пауза между ними':>18}{шапка}")
    for пауза in ПАУЗЫ_МС:
        смесь = np.concatenate([первый, тишина(пауза), второй])
        строка = "".join(f"{реплик(смесь, p):>7} " for p in пороги)
        print(f"  {пауза:>15} мс{строка}")

    print("\n— Монолог одного человека: на сколько кусков порвало (нужен 1)")
    строка = "".join(f"{реплик(монолог, p):>7} " for p in пороги)
    print(f"  {'':>18}{строка}")

    print("\n  VAD режет примерно на сотню миллисекунд позже порога: при 200 граница"
          "\n  проходит около 300 мс настоящей тишины. Паузу короче не режет ни один"
          "\n  разумный порог — это лечится разрезом по смене голоса, а не по тишине.")


if __name__ == "__main__":
    main()
