"""Поиск смены говорящего внутри реплики (app/diarization/turns.py).

Векторы синтетические: «голос» — случайное направление, «окно» — оно же с
шумом. Модели не нужны, тест проверяет логику разреза, а не качество ECAPA.
Качество на живом звуке меряет scripts/eval_turns.py.
"""
import numpy as np
import pytest

from app.config import Settings
from app.diarization.turns import HOP_S, WINDOW_S, turn_points, turn_times

DIM = 192
ПОРОГ = Settings(_env_file=None).speaker_turn_threshold


def единичный(v: np.ndarray) -> np.ndarray:
    return (v / np.linalg.norm(v)).astype(np.float32)


@pytest.fixture()
def rng() -> np.random.Generator:
    return np.random.default_rng(7)


def окна(rng, голоса: str, шум: float = 0.35) -> np.ndarray:
    """«ААББ» → четыре окна: два голосом А, два голосом Б, у каждого свой шум.

    Шум подобран так, чтобы окна одного голоса походили друг на друга на
    0.8–0.9 — как на живой записи, а не идеально.
    """
    направления = {буква: единичный(rng.standard_normal(DIM)) for буква in set(голоса)}
    return np.array([
        единичный(направления[буква] + шум * единичный(rng.standard_normal(DIM)))
        for буква in голоса
    ])


def test_монолог_не_режется(rng):
    """Один голос на всю реплику — ни одного разреза, сколько бы он ни шумел."""
    assert turn_points(окна(rng, "А" * 20), ПОРОГ) == []


def test_двое_встык_режутся_на_стыке(rng):
    """Смена голоса без всякой паузы — разрез ровно там, где начался второй."""
    assert turn_points(окна(rng, "АААААББББББ"), ПОРОГ) == [5]


def test_чужой_голос_островом_посередине_даёт_два_разреза(rng):
    """Главный случай, ради которого сравнение локальное.

    Первый вариант метода сравнивал всё слева со всем справа — и остров
    посередине не видел: любой один разрез оставлял смесь голосов по обе
    стороны. На записи подкаста так пропускались три реплики из десяти.
    """
    assert turn_points(окна(rng, "ААААББББАААА"), ПОРОГ) == [4, 8]


def test_одна_смена_даёт_один_разрез(rng):
    """Окно, попавшее на стык, смешивает оба голоса, и его отпечаток уходит в
    сторону от обоих (здесь это «Х» — третье направление). Тогда провал
    близости есть в двух соседних точках, и без подавления соседей одна смена
    давала бы два разреза и огрызок в полсекунды между ними.

    Первая версия теста брала резкую границу без смешанного окна — и не
    заметила, когда подавление соседей убрали из кода: на резкой границе провал
    бывает только в одной точке, подавлять нечего.
    """
    разрезы = turn_points(окна(rng, "ААААААХББББББ"), ПОРОГ)
    assert len(разрезы) == 1


def test_короткую_реплику_проверить_нечем(rng):
    """Меньше двух окон на сторону — сравнивать нечего, реплика не трогается."""
    assert turn_points(окна(rng, "АББ"), ПОРОГ) == []


def test_время_разреза_посередине_перекрытия_окон(rng):
    """Окна k-1 и k перекрываются на полшага; где внутри сменился голос, по
    отпечаткам не сказать — берётся середина перекрытия."""
    начало = 10.0
    [время] = turn_times(окна(rng, "АААААББББББ"), начало, ПОРОГ)
    окно_k = начало + 5 * HOP_S
    assert время == pytest.approx(окно_k + (WINDOW_S - HOP_S) / 2)
