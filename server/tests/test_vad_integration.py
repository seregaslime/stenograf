"""Интеграционный тест: настоящий silero-VAD на синтезированной речи.

Запуск (грузит модель VAD, нужен `say` — только macOS):
    .venv/bin/python -m pytest -m integration

Закрепляет порог тишины vad_min_silence_ms с двух сторон. Функции взяты из
scripts/eval_split.py, а не повторены: тест и замер должны мерить одно и то же.

VAD режет не на пороге, а примерно на сотню миллисекунд позже: при 200 граница
около 300 мс настоящей тишины, при 300 — около 400, при 400 — около 500. Поэтому
каждая проверка стоит посередине между соседними границами, с запасом 50 мс в
обе стороны. Первая версия теста стояла ровно на границе — и зеленела у
разработчика, но падала в CI на другой версии голосов.

Края синтезированных фраз обрезаются: `say` оставляет свою тишину, разную на
разных версиях голосов, и без обрезки пауза в тесте была бы не той, что написана.
"""
import shutil
import sys
from pathlib import Path

import numpy as np
import pytest

sys.path.append(str(Path(__file__).resolve().parent.parent / "scripts"))
import eval_split  # noqa: E402

from app.config import Settings  # noqa: E402

pytestmark = pytest.mark.integration


@pytest.fixture(scope="module")
def голоса(tmp_path_factory):
    if shutil.which("say") is None:
        pytest.skip("нет команды say (не macOS)")
    папка = tmp_path_factory.mktemp("split")
    return {
        "первый": eval_split.синтез(папка, *eval_split.ПЕРВЫЙ),
        "второй": eval_split.синтез(папка, *eval_split.ВТОРОЙ),
    }


@pytest.fixture(scope="module")
def порог() -> int:
    return Settings(_env_file=None).vad_min_silence_ms


def test_пауза_350_мс_внутри_речи_не_режет_фразу(голоса, порог):
    """Страж снизу: запинка внутри фразы — не конец реплики.

    Ровно эта ошибка случилась 16.09.2026. Порог опустили до 200 по замеру на
    синтезе, а живая запись встречи рассыпалась на куски: запинки внутри фразы
    («Э-э, у меня… проблема») как раз на 200–300 мс, и 200 их резал. На канале
    подкаста той же записи реплик стало 65 вместо 50, а коротких, до двух
    секунд, — 19 вместо 8. (Основное дробление той встречи — 202 реплики — дал
    не порог, а эхо колонок в микрофон; это отдельная беда.)

    Пауза 350 мс лежит между границами 300 (порог 200) и 400 (порог 300):
    опусти порог обратно на 200 — и тест упадёт.
    """
    речь = голоса["первый"]
    фраза = np.concatenate([речь, eval_split.тишина(350), речь])
    assert eval_split.реплик(фраза, порог) == 1


def test_двое_с_паузой_450_мс_становятся_двумя_репликами(голоса, порог):
    """Страж сверху: смена говорящего с заметной паузой режется.

    Пауза 450 мс лежит между границами 400 (порог 300) и 500 (порог 400):
    подними порог до 400 — и двое снова склеятся в одну реплику, которую
    целиком заберёт тот, кто говорил дольше.
    """
    смесь = np.concatenate([голоса["первый"], eval_split.тишина(450), голоса["второй"]])
    assert eval_split.реплик(смесь, порог) == 2
