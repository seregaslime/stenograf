"""Интеграционный тест: настоящий silero-VAD на синтезированной речи.

Запуск (грузит модель VAD, нужен `say` — только macOS):
    .venv/bin/python -m pytest -m integration

Закрепляет порог тишины vad_min_silence_ms. Функции взяты из
scripts/eval_split.py, а не повторены: тест и замер должны мерить одно и то же.

Первая версия этого теста проверяла паузу ровно на пороге — 200 мс при пороге
200 мс — и прошла у разработчика, но упала на раннере CI. Причин две: `say`
оставляет по краям фраз свою тишину, разную на разных версиях голосов, а VAD
режет не на пороге, а примерно на сотню миллисекунд позже. Исход на границе
решали десятки миллисекунд при окне VAD в 32 мс. Теперь края фраз обрезаются,
пауза в тесте настоящая, и каждая проверка стоит с запасом от границы.
"""
import shutil
import sys
from pathlib import Path

import numpy as np
import pytest

sys.path.append(str(Path(__file__).resolve().parent.parent / "scripts"))
import eval_split  # noqa: E402

from app.config import Settings  # noqa: E402

pytestmark = pytest.mark.integration


@pytest.fixture(scope="module")
def голоса(tmp_path_factory):
    if shutil.which("say") is None:
        pytest.skip("нет команды say (не macOS)")
    папка = tmp_path_factory.mktemp("split")
    return {
        "первый": eval_split.синтез(папка, *eval_split.ПЕРВЫЙ),
        "второй": eval_split.синтез(папка, *eval_split.ВТОРОЙ),
    }


@pytest.fixture(scope="module")
def порог() -> int:
    return Settings(_env_file=None).vad_min_silence_ms


def test_двое_с_паузой_350_мс_становятся_двумя_репликами(голоса, порог):
    """Пауза 350 мс между разными людьми режется.

    По замеру при пороге 200 разрез начинается с 300 мс настоящей тишины, при
    прежних 300 — с 400. Пауза 350 мс лежит посередине с запасом 50 мс в обе
    стороны: вернуть порог на 300 — и тест падает, двое снова склеиваются.
    """
    смесь = np.concatenate([голоса["первый"], eval_split.тишина(350), голоса["второй"]])
    assert eval_split.реплик(смесь, порог) == 2


def test_короткая_пауза_внутри_речи_одного_человека_не_режется(голоса, порог):
    """Пауза 150 мс внутри речи — не конец реплики.

    Это страж снизу, и честно о его пределах: он ловит сползание порога до ~100
    мс, где VAD уже нестабилен и рвёт речь как попало, но не отличает 150 от 200.
    Эти два значения расходятся в замере всего на 50 мс настоящей тишины —
    меньше, чем надёжно различает VAD с окном 32 мс, — и тест на эту разницу
    снова стоял бы на границе. Довод против 150 (монолог рвётся на четыре куска)
    записан замером в комментарии к порогу, а не тестом.
    """
    речь = голоса["первый"]
    монолог = np.concatenate([речь, eval_split.тишина(150), речь, eval_split.тишина(150), речь])
    assert eval_split.реплик(монолог, порог) == 1
