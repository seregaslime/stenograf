/**
 * Один хозяин у индексации на всё приложение.
 *
 * Зачем: считать векторы умеет `indexPending`, но она не помнит, что её уже
 * зовут. Экран «База знаний» и поиск на истории звали её каждый по-своему, и
 * два запуска шли одновременно: сервер отдаёт куски как несосчитанные, пока
 * первый запуск не сохранил источник целиком, поэтому второй честно считал те
 * же куски заново. На ПК это минуты работы модели впустую.
 *
 * Здесь запуск ровно один: второй вызов не начинает новый, а присоединяется к
 * идущему. Заодно прогресс перестал быть личным делом экрана — уход на другую
 * вкладку больше не прячет индексацию, потому что состояние живёт не в
 * компоненте.
 *
 * Хук рядом с состоянием намеренно: подписка через `useSyncExternalStore` —
 * единственный способ читать это состояние из React без гонок, и держать её
 * отдельно от самого состояния значило бы разносить одно решение по двум
 * файлам.
 */
import { useEffect, useSyncExternalStore } from "react";

import { api } from "../api/rest";
import { indexPending, type IndexProgress, type SearchApi } from "./search";
import { loadLlmSettings } from "./settings";

/** Сервер умеет отдать неиндексированное, принять векторы и сравнить их. */
export const searchApi: SearchApi = {
  pending: (model) => api.searchPending(model),
  index: (body) => api.searchIndex(body),
  query: (body) => api.searchQuery(body),
};

export interface IndexState {
  /** Идущая индексация; null — сейчас ничего не считается. */
  progress: IndexProgress | null;
  /** Когда начали: по нему считается «осталось столько-то». */
  startedAt: number;
  /** Чем кончился прошлый запуск; пустая строка — без ошибки. */
  error: string;
}

const ПОКОЙ: IndexState = { progress: null, startedAt: 0, error: "" };

let состояние: IndexState = ПОКОЙ;
let идущий: Promise<number> | null = null;
const подписчики = new Set<() => void>();

function сменить(новое: IndexState): void {
  состояние = новое;
  подписчики.forEach((известить) => известить());
}

export function subscribe(listener: () => void): () => void {
  подписчики.add(listener);
  return () => {
    подписчики.delete(listener);
  };
}

export function indexState(): IndexState {
  return состояние;
}

export function isIndexing(): boolean {
  return идущий !== null;
}

/**
 * Досчитать векторы для всего, чему их не хватает. Если индексация уже идёт,
 * возвращается её же обещание — второго счёта не будет.
 *
 * Обещание не отказывает: причина неудачи ложится в `error` состояния, и её
 * показывают оба экрана. Иначе запуск, которого никто не ждёт (а такой будет —
 * автоматический), ронял бы приложение необработанным отказом.
 *
 * `ожидается` — сколько кусков ждёт по сводке: сервер отвечает не мгновенно, и
 * без этой подсказки плашка успевает мигнуть «кусок 0 из 0».
 */
export function startIndexing(model: string, ожидается = 0): Promise<number> {
  if (идущий) return идущий;
  const начало = Date.now();
  сменить({ progress: { chunksDone: 0, chunksTotal: ожидается, source: "" }, startedAt: начало, error: "" });
  идущий = indexPending(searchApi, loadLlmSettings(), model, (шаг) =>
    сменить({ progress: шаг, startedAt: начало, error: "" }))
    .then((посчитано) => {
      // Снимаем признак «идёт» до рассылки: подписчик, который среагирует на
      // конец запуском следующей индексации, иначе получил бы это же, уже
      // завершённое обещание и решил бы, что всё посчитано.
      идущий = null;
      сменить(ПОКОЙ);
      return посчитано;
    })
    .catch((exc: Error) => {
      идущий = null;
      // Сохранённое не пропадает: повторный запуск продолжит со следующего
      // источника. Своё сообщение модели не всегда кончается точкой
      // («…ollama pull имя») — без неё приписка склеивалась с командой.
      const причина = exc.message.trim().replace(/[.!?…]?$/, ".");
      сменить({ ...ПОКОЙ, error: `${причина} Уже посчитанное сохранено — можно продолжить.` });
      return 0;
    });
  return идущий;
}

/** Состояние индексации в React: перерисовка на каждый шаг, откуда бы он ни шёл. */
export function useIndexing(): IndexState {
  return useSyncExternalStore(subscribe, indexState);
}

let встречаИдёт = false;

/**
 * Идёт ли сейчас встреча. Знать это индексации обязательно: эмбеддинги и
 * подсказки во время встречи считает одна и та же Ollama, а она отвечает по
 * очереди. Замер 17.09.2026 — около 0.2 с на каждый текст независимо от длины;
 * документ на сотню кусков занимает её на полминуты, и подсказка, которая
 * нужна через несколько секунд после реплики, придёт после.
 */
export function setMeetingLive(живая: boolean): void {
  встречаИдёт = живая;
}

/**
 * Досчитать то, чего не хватает, — но только если сейчас никому не мешаем.
 * Этим отличается от `startIndexing`: тот выполняет прямую просьбу человека и
 * не отказывает, а этот срабатывает сам и потому обязан быть тихим.
 *
 * Сам считает только новое — свежую встречу, только что загруженный документ.
 * Пересчёт после смены модели эмбеддингов сам не начинает никогда: он стоит
 * столько же, сколько индексация всей базы с нуля, и решение о нём человек
 * принимает на экране «База знаний», где ему показано, сколько это займёт.
 * Поэтому, если хоть один источник ждёт из-за смены модели, тихий запуск
 * отменяется целиком: разделить «новое» и «пересчёт» в одном проходе нельзя —
 * сервер отдаёт то и другое одним списком.
 */
export async function autoIndex(model: string): Promise<void> {
  if (встречаИдёт || !model) return;
  const сводка = await api.knowledgeStatus(model).catch(() => null);
  if (!сводка) return;
  const ждут = [...сводка.meetings, ...сводка.documents].filter((и) => и.status === "waiting");
  if (!ждут.length || ждут.some((и) => и.chunks_other_models > 0)) return;
  if (встречаИдёт) return;  // встреча могла начаться, пока сервер отвечал
  void startIndexing(model);
}

/**
 * Автоматическая индексация приложения: считает, когда появился повод и когда
 * это не мешает.
 *
 * Поводов ровно три, и все они — события, а не опрос: приложение дождалось
 * сервера, закончилась встреча, сменилась модель эмбеддингов. Опрашивать
 * сервер по таймеру не нужно — новые куски появляются только после встречи или
 * после загрузки документа, а загрузка зовёт `autoIndex` сама.
 *
 * Смена модели — повод посмотреть, а не посчитать: полный пересчёт `autoIndex`
 * не начинает, так что этот повод обычно кончается ничем. Оставлен потому, что
 * новая модель может оказаться той же, которой всё уже посчитано.
 */
export function useAutoIndexing(серверНаСвязи: boolean, идётВстреча: boolean): void {
  const model = loadLlmSettings().embedModel;
  useEffect(() => {
    // Признак встречи ставится здесь, а не при отрисовке: за окончанием встречи
    // следит тот же эффект, который решает, не пора ли считать
    setMeetingLive(идётВстреча);
    if (серверНаСвязи && !идётВстреча) void autoIndex(model);
  }, [серверНаСвязи, идётВстреча, model]);
}
