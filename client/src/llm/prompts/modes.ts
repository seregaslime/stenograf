/**
 * Типы встреч и общие куски промптов. Перенесено с сервера дословно: формулировки
 * подбирались на живых встречах, и «улучшение» текста здесь — это изменение
 * поведения модели без замера.
 */
import type { MeetingMode } from "../../types";

export interface ModeInfo {
  key: MeetingMode;
  /** Подставляется в промпт и показывается в интерфейсе. */
  label: string;
  /** На что смотреть в этом типе встречи (коротко!). */
  hintFocus: string;
}

export const MODES: Record<MeetingMode, ModeInfo> = {
  work: {
    key: "work",
    label: "рабочая встреча / планёрка",
    hintFocus:
      "Следи за задачами без ответственного и срока, за решениями без критерия " +
      "готовности, за блокерами и зависимостями, которые упомянули и не разобрали.",
  },
  interview: {
    key: "interview",
    label: "собеседование (ты помогаешь тому, кто проходит собеседование)",
    hintFocus:
      "Владелец микрофона — кандидат, помогай ему. Если интервьюер задал " +
      "вопрос — дай суть ответа тезисами. Если прозвучал незнакомый термин " +
      "или технология — коротко объясни. Замечай вопросы, которые стоит " +
      "задать самому (задачи, команда, процессы, условия).",
  },
  negotiation: {
    key: "negotiation",
    label: "переговоры",
    hintFocus:
      "Следи за условиями (цена, сроки, объём) и их изменениями по ходу, за " +
      "уступкой без встречной уступки, за расплывчатыми обязательствами " +
      "(«постараемся», «в ближайшее время»), за незаданными вопросами о " +
      "бюджете, полномочиях и сроке решения.",
  },
};

export const DEFAULT_MODE: MeetingMode = "work";

/** Неизвестный или пустой тип — рабочая встреча. Старый клиент поля не шлёт. */
export function normalizeMode(value: string | null | undefined): MeetingMode {
  return value && value in MODES ? (value as MeetingMode) : DEFAULT_MODE;
}

export function modeLabel(key: string | null | undefined): string {
  return MODES[normalizeMode(key)].label;
}

