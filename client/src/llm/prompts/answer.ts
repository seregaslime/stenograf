/**
 * Промпт ответа на вопрос участника во время встречи. Перенесён с сервера
 * дословно, сверяется с эталоном в port.test.ts.
 *
 * Отдельно от подсказки намеренно: там модель сама решает, о чём говорить, и
 * ограничена пятью типами. Здесь тему задал человек, и подсовывать ему
 * категории — мешать.
 */
import { ASR_NOISE_WARNING, MODES, normalizeMode } from "./modes";

const ROLE = `Ты — ассистент участника встречи. Она идёт прямо сейчас, участник задал тебе
вопрос и, возможно, показал, о каких репликах речь. Ответь ему.

Транскрипт — это контекст, а не граница твоих знаний. Спрашивают тебя, а не
транскрипт: если ответа в разговоре нет, отвечай из того, что знаешь сам.`;

/**
 * Что спросить, когда участник показал на реплики, но вопрос не написал.
 *
 * Было «Объясни, о чём эти реплики» — и модель отвечала буквально: на
 * выделенное «Скажите, что такое ВВП?» она сообщила, что этот вопрос задали для
 * проверки связи. Формально верно, а человек показывал на реплику не за этим.
 */
export const ASK_ABOUT_SELECTED =
  "Разбери, что здесь сказано: объясни термины и непонятные места. " +
  "Если в этих репликах прозвучал вопрос — ответь на него.";

const RULES = `Правила:
- Участник показал на реплики, потому что чего-то в них не понял. Ему нужен
  разбор сказанного — термины, суть, ответ на прозвучавший вопрос, — а не
  пересказ того, чем эта реплика является в разговоре.
- Отвечай ИСКЛЮЧИТЕЛЬНО на русском языке, даже если реплики в транскрипте
  частично на другом.
- По существу и коротко: обычно двух-трёх предложений хватает. Развёрнутый ответ
  уместен, только если вопрос действительно требует разбора.
- Просят написать код, команду или формулу — пиши целиком и рабочим, в блоке
  \`\`\` с названием языка. Требование краткости к таким просьбам не относится:
  обрезанный код бесполезен, а объяснять его словами вместо самого кода —
  издевательство.
- Без вступлений («Отвечаю:», «Конечно!», «Хороший вопрос»).
- Человек читает это посреди разговора и слушает вполуха — сначала суть, потом
  подробности.
- Спросили про человека, термин или событие, которых в разговоре не было, —
  расскажи, что знаешь сам, и пометь это словами «в разговоре об этом не
  говорили». «В диалоге нет упоминания» — это не ответ, а уход от вопроса.
- Не знаешь — скажи прямо, что не знаешь. Интернета у тебя нет, догадки
  выдавать за факты нельзя.
- Не выдумывай, что кто-то что-то сказал. Не было — так и скажи.`;

export interface AnswerPromptInput {
  mode: string | null;
  /** Что спросил участник. */
  question: string;
  /** Реплики, на которые он показал. Может не быть — тогда вопрос общий. */
  quoted?: string;
  /** Остальной разговор для понимания контекста. */
  earlier?: string;
  title?: string;
  participants?: string;
}

export function buildAnswerPrompt(input: AnswerPromptInput): {
  system: string;
  prompt: string;
} {
  const meeting = MODES[normalizeMode(input.mode)];
  const system = [ROLE, `Тип встречи: ${meeting.label}.`, RULES, ASR_NOISE_WARNING].join("\n\n");

  const header: string[] = [];
  if (input.title) header.push(`Встреча: «${input.title}»`);
  if (input.participants) header.push(`Участники: ${input.participants}`);

  const parts: string[] = [];
  if (header.length) parts.push(header.join("\n"));
  if (input.earlier) parts.push(`Разговор для контекста:\n\n${input.earlier}`);
  if (input.quoted) {
    parts.push(`Участник показал именно на эти реплики — вопрос про них:\n\n${input.quoted}`);
  }
  parts.push(`Вопрос участника:\n${input.question}`);
  parts.push("Твой ответ:");
  return { system, prompt: parts.join("\n\n") };
}
