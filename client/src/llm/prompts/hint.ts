/**
 * Промпт подсказки во время встречи. Перенесён с сервера дословно: формулировки
 * подбирались на живых встречах, и сверяются с эталоном в port.test.ts.
 */
import { ASR_NOISE_WARNING, MODES, normalizeMode } from "./modes";

export const SKIP_TOKEN = "SKIP";

const ROLE = `Ты — молчаливый ассистент на встрече. Ты видишь расшифровку разговора в реальном
времени и вмешиваешься ТОЛЬКО когда действительно есть что сказать.`;

const CATEGORIES = `Разрешены ровно пять типов подсказки:
1. ОТВЕТ — прозвучал прямой вопрос, на который никто не ответил (в том числе
   «что такое X?»). Дай ответ ПО СУЩЕСТВУ, а не совет у кого-то спросить.
2. ТЕРМИН — прозвучали термин или аббревиатура, которые часть участников может
   не знать. Объясни так, чтобы стало понятно человеку не в теме: расшифровка
   плюс что это значит на практике. Одной расшифровки обычно мало.
3. РИСК — в сказанном есть противоречие, фактическая ошибка или неучтённый риск.
4. ПРОБЕЛ — важный вопрос задали, но обсуждение ушло в сторону; или решение
   приняли без ключевого условия.
5. ЗАДАЧА — прозвучала договорённость без ответственного или без срока.`;

const RULES = `Правила:
- Одна подсказка, по-русски. Обычно хватает двух предложений, но жёсткого
  потолка нет: если по существу есть что добавить — добавь. Ответ на вопрос или
  определение термина лучше дать целиком, чем оборвать на половине.
- Длина оправдана только содержанием. Человек читает подсказку, пока слушает
  разговор, и каждое предложение ни о чём он читает вместо того, чтобы слушать.
- Без вступлений («Подсказка:», «Совет:», «Обратите внимание:»).
- Не пересказывай то, что и так только что сказали.
- Не выдумывай факты. Не уверен в ответе — не отвечай.
- Не задавай вопрос ради вопроса.`;

const SKIP_RULE = `Если ни один из пяти типов не подходит — ответь ровно одним словом: ${SKIP_TOKEN}.
Молчать нормально. ${SKIP_TOKEN} лучше, чем бесполезная подсказка.`;

const FORCE_RULE = `Пользователь явно нажал «Подсказать сейчас» — ответ обязателен.
Выбери самое полезное из пяти типов. Если ничего критичного нет — одним
предложением скажи, на чём разговор сейчас и какой следующий шаг напрашивается.`;

// Первые два примера и SKIP идут всегда; остальные — только в развёрнутом
// варианте. Пример со SKIP обязателен: без него модель считает молчание отказом
// от работы.
const EXAMPLES_CORE = `Фрагмент: «Иван: у нас по SLA девять девяток. / Мария: а что такое SLA?»
Хорошо: «SLA — соглашение об уровне сервиса; 99,9 % — это не более ~43 минут простоя в месяц.»
Плохо:  «Уточните у Ивана, что он имеет в виду под SLA.»  ← просит спросить вместо ответа

Фрагмент: «Пётр: релиз выкатим в пятницу. / Анна: ок.»
Хорошо: «Релиз в пятницу — кто дежурит на выходных, если что-то отвалится?»
Плохо:  «Обсудите план релиза подробнее.»  ← вода`;

const EXAMPLES_EXTRA = `Фрагмент: «Аня: я пришлю макеты. / Олег: спасибо.»
Хорошо: «У задачи «прислать макеты» нет срока — до какого числа?»

Фрагмент: «Игорь: база у нас на одном сервере, реплики нет. / Лиза: ну ок, потом добавим.»
Хорошо: «База без реплики — единая точка отказа; стоит зафиксировать это как риск с владельцем.»`;

const EXAMPLE_SKIP = `Фрагмент: «Иван: …а мы на неделю в отпуск съездили. / Мария: здорово!»
Хорошо: ${SKIP_TOKEN}`;

export interface HintPromptInput {
  mode: string | null;
  /** То, на что НАДО реагировать — новое с прошлой подсказки. */
  transcript: string;
  /** Подсказки, которые уже давали: их не повторять. */
  previous: string;
  /** Что было раньше: нужно для понимания, реагировать не надо. */
  earlier?: string;
  title?: string;
  participants?: string;
  /** Развёрнутый вариант для API: контекст не жалеем. */
  detailed?: boolean;
  /** false — кнопка «Подсказать сейчас», ответ обязателен. */
  allowSkip?: boolean;
}

export function buildHintPrompt(input: HintPromptInput): { system: string; prompt: string } {
  const meeting = MODES[normalizeMode(input.mode)];
  const allowSkip = input.allowSkip ?? true;
  const system = [
    ROLE,
    CATEGORIES,
    `Тип встречи: ${meeting.label}.\n${meeting.hintFocus}`,
    RULES,
    ASR_NOISE_WARNING,
    allowSkip ? SKIP_RULE : FORCE_RULE,
  ].join("\n\n");

  const examples = [EXAMPLES_CORE];
  if (input.detailed) examples.push(EXAMPLES_EXTRA);
  // В режиме «ответ обязателен» пример со SKIP только собьёт модель
  if (allowSkip) examples.push(EXAMPLE_SKIP);

  const header: string[] = [];
  if (input.title) header.push(`Встреча: «${input.title}»`);
  if (input.participants) header.push(`Участники: ${input.participants}`);

  const parts = ["Примеры.\n\n" + examples.join("\n\n")];
  if (header.length) parts.push(header.join("\n"));
  if (input.earlier) {
    parts.push(
      "Ранее в разговоре — только для понимания контекста, реагировать на это " +
        "НЕ надо (в квадратных скобках — что ты уже подсказывал):\n\n" +
        `${input.earlier}`,
    );
    parts.push(`НОВОЕ с прошлой подсказки — реагируй только на это:\n\n${input.transcript}`);
  } else {
    parts.push(`Последний фрагмент обсуждения:\n\n${input.transcript}`);
  }
  parts.push(
    "Ты уже давал такие подсказки — не повторяй их и не пиши похожее по смыслу:\n" +
      `${input.previous}`,
  );
  parts.push("Твоя подсказка:");
  return { system, prompt: parts.join("\n\n") };
}

const STRIP_CHARS = " \t\n\r`*_\"'«»";
const PREFIXES = ["подсказка:", "совет:", "ответ:", "hint:"];

/** Обрезает по краям любые из перечисленных символов (аналог str.strip в Python). */
function strip(text: string, chars: string): string {
  let start = 0;
  let end = text.length;
  while (start < end && chars.includes(text[start])) start += 1;
  while (end > start && chars.includes(text[end - 1])) end -= 1;
  return text.slice(start, end);
}

/**
 * Разбирает ответ модели. null — «промолчала», такое человеку не показываем.
 *
 * Мелкие модели редко отвечают ровно одним словом, поэтому разбор толерантный.
 * Но и не слишком жадный: подсказка, где слово skip встречается внутри текста,
 * должна дойти до человека целиком.
 */
export function parseHint(raw: string | null | undefined, minChars = 12): string | null {
  // Пусто — в том числе когда весь ответ ушёл в размышления и его вырезали
  if (!raw) return null;
  let text = strip(strip(raw, " \t\n\r"), STRIP_CHARS).trim();
  const lowered = text.toLowerCase();
  for (const prefix of PREFIXES) {
    if (lowered.startsWith(prefix)) {
      text = text.slice(prefix.length).trim();
      // «Подсказка: уточните…» → «Уточните…»
      if (text.slice(0, 1) !== text.slice(0, 1).toUpperCase()) {
        text = text[0].toUpperCase() + text.slice(1);
      }
      break;
    }
  }
  if (!text) return null;
  // SKIP засчитываем, только если это первое слово и после него почти ничего нет
  const пробел = text.indexOf(" ");
  const first = пробел === -1 ? text : text.slice(0, пробел);
  const rest = пробел === -1 ? "" : text.slice(пробел + 1);
  if (strip(first, STRIP_CHARS + ".,!;:—-").toUpperCase() === SKIP_TOKEN && rest.length < 15) {
    return null;
  }
  // «Ок.», «Нет.», «—» — считаем молчанием
  return text.length < minChars ? null : text;
}
