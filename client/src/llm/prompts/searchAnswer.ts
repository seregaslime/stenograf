/**
 * Промпт ответа по прошлым встречам и документам базы знаний. Перенесён с
 * сервера дословно и сверяется с эталоном в port.test.ts; 17.09.2026 изменён
 * намеренно — появились документы (пункт 5а), см. ниже.
 *
 * Роль здесь отдельная от ответа участнику, и разница принципиальная: там
 * встреча идёт прямо сейчас, транскрипт — контекст, а не граница знаний, и
 * модели прямо разрешено отвечать из общих знаний. Здесь спрашивают про
 * договорённости, и ответ «из общих знаний» — это выдуманная договорённость,
 * которой никто не давал.
 */
import { ASR_NOISE_WARNING } from "./modes";

// Документы в роли и в правиле ссылок — не для красоты. Проверка на qwen3:4b:
// промпт знал только встречи, и на фрагмент регламента модель ответила «на
// встрече 14 августа в регламенте указано…» — дату взяла из примера в правилах,
// хотя встречи с такой датой среди фрагментов не было (1 ответ из 4).
// С документами в роли и ссылках модель стала комментировать фрагменты без
// ответа — «в записях встреч и документах этого нет» после верного ответа по
// встрече, 2 из 3. Уточнение «не упоминай фрагменты без ответа» это сняло:
// 3 из 3 чисто по встрече, 3 из 3 со ссылкой на документ по названию.
const ROLE = `Ты помогаешь вспомнить, что обсуждали на прошлых встречах и что записано в
документах человека. Тебе дали фрагменты записей встреч и документов, найденные
по вопросу человека, и сам вопрос.

Отвечай ТОЛЬКО по этим фрагментам. Ты не помнишь встреч и не знаешь ничего,
кроме показанного.`;

const RULES = `Правила:
- Если ответа нет ни в одном фрагменте — так и скажи: «в записях встреч и
  документах этого нет». Фрагменты, где ответа нет, в ответе не упоминай.
  Не достраивай ответ из общих знаний: речь о том, о чём договорились люди,
  и придуманная договорённость хуже её отсутствия.
- Ссылайся на источник, чтобы человек мог проверить. На встречу — с датой из
  заголовка её фрагмента: «на встрече 14 августа решили…». На документ — по
  названию: «в документе «Регламент» сказано…». У документа даты нет, не
  придумывай её.
- Коротко, обычно двух-трёх предложений достаточно.
- Отвечай на русском языке, даже если фрагменты частично на другом.
- Без вступлений («Отвечаю:», «Конечно!»).
- Фрагменты — из разных разговоров и могут противоречить друг другу. Если
  так — скажи об этом, а не выбирай удобный.`;

/** Кусок разговора из выдачи поиска. */
export interface SearchHitLike {
  document_title?: string | null;
  meeting_title?: string | null;
  started_at?: string | null;
  start_s?: number | null;
  text?: string;
}

export function buildSearchAnswerPrompt(
  question: string,
  found: SearchHitLike[],
): { system: string; prompt: string } {
  const system = [ROLE, RULES, ASR_NOISE_WARNING].join("\n\n");

  const фрагменты = found.map((кусок) => {
    // Документ базы знаний: ни даты встречи, ни минуты у него нет. Правила
    // промпта не тронуты — фрагменты встреч уходят модели дословно как раньше,
    // а сверка с эталоном (port.test.ts) это держит.
    if (кусок.document_title) {
      return `[Документ «${кусок.document_title}»]\n${кусок.text ?? ""}`;
    }
    const дата = (кусок.started_at ?? "").slice(0, 10);
    const минута = Math.trunc(кусок.start_s ?? 0);
    const время = `${Math.trunc(минута / 60)}:${String(минута % 60).padStart(2, "0")}`;
    return (
      `[Встреча «${кусок.meeting_title ?? ""}»${дата ? ", " + дата : ""}, ${время}]\n` +
      `${кусок.text ?? ""}`
    );
  });

  const prompt = [
    фрагменты.length ? "Найденные фрагменты записей:" : "Ничего не найдено.",
    ...фрагменты,
    `Вопрос:\n${question}`,
    "Твой ответ:",
  ].join("\n\n");
  return { system, prompt };
}
