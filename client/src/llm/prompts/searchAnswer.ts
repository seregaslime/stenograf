/**
 * Промпт ответа по прошлым встречам. Перенесён с сервера дословно, сверяется с
 * эталоном в port.test.ts.
 *
 * Роль здесь отдельная от ответа участнику, и разница принципиальная: там
 * встреча идёт прямо сейчас, транскрипт — контекст, а не граница знаний, и
 * модели прямо разрешено отвечать из общих знаний. Здесь спрашивают про
 * договорённости, и ответ «из общих знаний» — это выдуманная договорённость,
 * которой никто не давал.
 */
import { ASR_NOISE_WARNING } from "./modes";

const ROLE = `Ты помогаешь вспомнить, что обсуждали на прошлых встречах. Тебе дали фрагменты
записей, найденные по вопросу человека, и сам вопрос.

Отвечай ТОЛЬКО по этим фрагментам. Ты не помнишь встреч и не знаешь ничего,
кроме показанного.`;

const RULES = `Правила:
- Если во фрагментах ответа нет — так и скажи: «в записях встреч этого нет».
  Не достраивай ответ из общих знаний: речь о том, о чём договорились люди,
  и придуманная договорённость хуже её отсутствия.
- Ссылайся на встречу и дату, чтобы человек мог проверить: «на встрече
  14 августа решили…».
- Коротко, обычно двух-трёх предложений достаточно.
- Отвечай на русском языке, даже если фрагменты частично на другом.
- Без вступлений («Отвечаю:», «Конечно!»).
- Фрагменты — из разных разговоров и могут противоречить друг другу. Если
  так — скажи об этом, а не выбирай удобный.`;

/** Кусок разговора из выдачи поиска. */
export interface SearchHitLike {
  meeting_title?: string;
  started_at?: string | null;
  start_s?: number;
  text?: string;
}

export function buildSearchAnswerPrompt(
  question: string,
  found: SearchHitLike[],
): { system: string; prompt: string } {
  const system = [ROLE, RULES, ASR_NOISE_WARNING].join("\n\n");

  const фрагменты = found.map((кусок) => {
    const дата = (кусок.started_at ?? "").slice(0, 10);
    const минута = Math.trunc(кусок.start_s ?? 0);
    const время = `${Math.trunc(минута / 60)}:${String(минута % 60).padStart(2, "0")}`;
    return (
      `[Встреча «${кусок.meeting_title ?? ""}»${дата ? ", " + дата : ""}, ${время}]\n` +
      `${кусок.text ?? ""}`
    );
  });

  const prompt = [
    фрагменты.length ? "Найденные фрагменты записей:" : "Ничего не найдено.",
    ...фрагменты,
    `Вопрос:\n${question}`,
    "Твой ответ:",
  ].join("\n\n");
  return { system, prompt };
}
