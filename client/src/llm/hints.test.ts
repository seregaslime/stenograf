/**
 * Движок подсказок: когда дёргать модель, что ей показывать и что делать с
 * ответом. Модель подменена — проверяется решающая логика, а не формулировки
 * (за них отвечает сверка с эталоном в prompts/port.test.ts).
 */
import { describe, expect, it, vi } from "vitest";

import { HintEngine } from "./hints";
import { LlmError } from "./ollama";
import { LlmRouter, type LlmSettings } from "./router";

const НАСТРОЙКИ: LlmSettings = {
  provider: "local",
  ollamaUrl: "http://192.168.3.10:11434",
  localSummaryModel: "qwen3:4b",
  localHintsModel: "qwen3:1.7b",
  apiBaseUrl: "",
  apiKey: "",
  apiSummaryModel: "",
  apiHintsModel: "",
  embedModel: "bge-m3",
};

/** Движок с подменённой моделью и управляемыми часами. */
function стенд(
  ответ: (prompt: string, номер: number) => string,
  settings = НАСТРОЙКИ,
  задержать?: (номер: number) => Promise<void>,
) {
  const llm = new LlmRouter(settings);
  const промпты: string[] = [];
  vi.spyOn(llm, "generate").mockImplementation(async (_role, prompt) => {
    промпты.push(prompt);
    const номер = промпты.length;
    if (задержать) await задержать(номер);
    return ответ(prompt, номер);
  });

  const подсказки: string[] = [];
  const ошибки: string[] = [];
  let время = 1000;
  const движок = new HintEngine({
    llm,
    mode: "work",
    title: "Планёрка",
    participants: () => "Сергей (5 реплик)",
    onHint: (t) => подсказки.push(t),
    onError: (m) => ошибки.push(m),
    now: () => время,
  });
  движок.enabled = true;
  const наговорить = (сколько: number) => {
    for (let i = 0; i < сколько; i += 1) {
      движок.push("Сергей", `реплика номер ${i}, в ней достаточно текста для порога`);
    }
  };
  return { движок, промпты, подсказки, ошибки, наговорить, идёт: (с: number) => (время += с) };
}

describe("когда дёргать модель", () => {
  it("молчит, пока разговора мало", async () => {
    const { движок, промпты } = стенд(() => "подсказка");
    движок.push("Сергей", "привет");
    await движок.tick();
    expect(промпты).toHaveLength(0);
  });

  it("не частит: между подсказками выдерживается пауза", async () => {
    const { движок, промпты, наговорить, идёт } = стенд(() => "Уточните срок задачи у Ивана");
    наговорить(5);
    await движок.tick();
    expect(промпты).toHaveLength(1);

    наговорить(5); // текста снова много, но времени прошло мало
    await движок.tick();
    expect(промпты).toHaveLength(1);

    идёт(20);
    await движок.tick();
    expect(промпты).toHaveLength(2);
  });

  it("молчание модели удлиняет паузу, а серия молчаний — сильнее", async () => {
    const { движок, промпты, подсказки, наговорить, идёт } = стенд(() => "SKIP");
    наговорить(5);
    await движок.tick();
    идёт(9); // после первого SKIP пауза 8 секунд — уже можно
    наговорить(3);
    await движок.tick();
    expect(промпты).toHaveLength(2);

    идёт(9); // после второго SKIP пауза уже 16 — рано
    наговорить(3);
    await движок.tick();
    expect(промпты).toHaveLength(2);
    expect(подсказки).toHaveLength(0); // молчание человеку не показываем
  });
});

describe("что уходит модели", () => {
  it("новое отделено от контекста, свои подсказки вплетены", async () => {
    const { движок, промпты, наговорить, идёт } = стенд(() => "Уточните срок задачи у Ивана");
    наговорить(5);
    await движок.tick();

    идёт(20);
    наговорить(5);
    await движок.tick();

    const второй = промпты[1];
    expect(второй).toContain("НОВОЕ с прошлой подсказки");
    expect(второй).toContain("[ты подсказал: Уточните срок задачи у Ивана]");
  });

  it("по кнопке разговор показывается целиком, без деления", async () => {
    const { движок, промпты, наговорить, идёт } = стенд(() => "Уточните срок задачи у Ивана");
    наговорить(5);
    await движок.tick();
    идёт(20);
    наговорить(5);
    await движок.emit(true);

    expect(промпты[1]).not.toContain("НОВОЕ с прошлой подсказки");
    expect(промпты[1]).toContain("Последний фрагмент обсуждения");
  });
});

describe("что делать с ответом", () => {
  it("почти-дубль недавней подсказки человеку не показывается", async () => {
    const { движок, подсказки, наговорить, идёт } = стенд((_p, номер) =>
      номер === 1 ? "Уточните срок задачи у Ивана" : "Уточните срок этой задачи у Ивана",
    );
    наговорить(5);
    await движок.tick();
    идёт(20);
    наговорить(5);
    await движок.tick();

    expect(подсказки).toEqual(["Уточните срок задачи у Ивана"]);
  });

  it("по кнопке дубль показывается: человек попросил явно", async () => {
    const { движок, подсказки, наговорить, идёт } = стенд(() => "Уточните срок задачи у Ивана");
    наговорить(5);
    await движок.tick();
    идёт(20);
    наговорить(5);
    await движок.emit(true);

    expect(подсказки).toHaveLength(2);
  });

  it("по кнопке молчание модели объясняется, а не пропадает", async () => {
    const { движок, ошибки, наговорить } = стенд(() => "SKIP");
    наговорить(5);
    await движок.emit(true);
    expect(ошибки).toEqual(["Модель не нашла, что подсказать. Попробуйте позже."]);
  });
});

describe("ошибки связи", () => {
  it("один сбой не выключает подсказки, но откладывает следующую", async () => {
    const { движок, ошибки, промпты, наговорить, идёт } = стенд(() => {
      throw new LlmError("Модель недоступна");
    });
    наговорить(5);
    await движок.tick();
    expect(ошибки).toEqual(["Модель недоступна"]);
    expect(движок.enabled).toBe(true);

    идёт(20); // пауза после сбоя больше обычной — ещё рано
    наговорить(5);
    await движок.tick();
    expect(промпты).toHaveLength(1);
  });

  it("после пяти сбоев подряд подсказки гаснут с объяснением", async () => {
    const { движок, ошибки, наговорить, идёт } = стенд(() => {
      throw new LlmError("Модель недоступна");
    });
    for (let i = 0; i < 5; i += 1) {
      наговорить(5);
      идёт(200); // пережидаем бэкофф
      await движок.tick();
    }
    expect(движок.enabled).toBe(false);
    expect(ошибки.at(-1)).toMatch(/приостановлены/);
  });
});

describe("вопрос участника", () => {
  it("выделенные реплики уходят отдельным блоком", async () => {
    const { движок, промпты, наговорить } = стенд(() => "GIL — глобальная блокировка");
    наговорить(5);
    const ответ = await движок.answer("что такое GIL?", "[00:10] Иван: расскажи про GIL");

    expect(ответ).toBe("GIL — глобальная блокировка");
    expect(промпты[0]).toContain("Участник показал именно на эти реплики");
    expect(промпты[0]).toContain("Вопрос участника:\nчто такое GIL?");
  });

  it("пустой ответ модели — ошибка, а не пустая реплика в чате", async () => {
    const { движок, наговорить } = стенд(() => "   ");
    наговорить(5);
    await expect(движок.answer("вопрос", "")).rejects.toThrow(/пустой ответ/);
  });
});

describe("швы, которые не ловились по отдельности", () => {
  const тариф: LlmSettings = {
    ...НАСТРОЙКИ,
    provider: "api",
    apiBaseUrl: "https://api.groq.com/openai/v1",
    apiKey: "ключ",
    apiSummaryModel: "gpt-oss-120b",
    apiHintsModel: "gpt-oss-20b",
    tpmLimits: { "gpt-oss-20b": 8000 },
  };

  it("одной подсказке достаётся доля тарифа, а не весь минутный лимит", () => {
    // Подсказок за минуту до четырёх (минимальный интервал 15 с). Отдав каждой
    // весь лимит, мы вчетверо превысили бы тариф: первая прошла бы, остальные
    // получили бы отказ, и подсказки погасли бы после пяти ошибок.
    const llm = new LlmRouter(тариф);
    const весьЛимит = llm.tpmLimit("gpt-oss-20b");
    expect(llm.budget.hintsTokens).toBe(Math.trunc(весьЛимит / 4));
    expect(llm.budget.hintsTokens).toBeLessThan(весьЛимит);
  });

  it("окно разговора считается от доли, а не от всего лимита", async () => {
    const { движок, промпты, наговорить } = стенд(() => "Уточните срок задачи", тариф);
    наговорить(400); // разговора заведомо больше любого бюджета
    await движок.tick();

    // Промпт целиком должен укладываться в долю тарифа с запасом на ответ
    const токенов = промпты[0].length / 2.5;
    expect(токенов).toBeLessThan(new LlmRouter(тариф).budget.hintsTokens);
  });

  it("кнопка отменяет фоновую подсказку, а не показывает обе", async () => {
    // Фоновый запрос держим до тех пор, пока человек не нажмёт кнопку: так
    // воспроизводится гонка, ради которой сервер снимал фоновую задачу.
    let отпустить = () => {};
    const держим = new Promise<void>((готово) => { отпустить = готово; });
    const { движок, подсказки } = стенд((prompt, номер) => {
      void prompt;
      return номер === 1 ? "фоновая подсказка про сроки" : "ответ по кнопке про сроки";
    }, НАСТРОЙКИ, async (номер) => { if (номер === 1) await держим; });

    for (let i = 0; i < 5; i += 1) {
      движок.push("Сергей", `реплика номер ${i}, в ней достаточно текста для порога`);
    }
    const фоновая = движок.tick();
    await Promise.resolve();
    const покнопке = движок.emit(true);
    отпустить();
    await Promise.all([фоновая, покнопке]);

    expect(подсказки).toEqual(["ответ по кнопке про сроки"]);
  });
});
